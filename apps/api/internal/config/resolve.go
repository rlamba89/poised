package config

import (
	"context"
	"errors"
	"fmt"
	"strings"
)

// AWS reads a deployment's secrets. internal/serve passes the real SSM and Secrets Manager
// clients; tests pass a fake.
type AWS interface {
	// Parameter is an SSM Parameter Store value, decrypted if it's a SecureString.
	Parameter(ctx context.Context, name string) (string, error)
	// Secret is a Secrets Manager secret's string, by ARN or name.
	Secret(ctx context.Context, id string) (string, error)
}

// fromAWS are the values a deployment keeps in AWS instead of its environment (plan F3 Step 3):
// the environment variable `via` names where the value of `name` is.
var fromAWS = []struct {
	name, via string
	secret    bool // Secrets Manager; otherwise SSM Parameter Store
}{
	{name: "DATABASE_URL", via: "DATABASE_URL_PARAM"},             // a SecureString that make aws-setup stores
	{name: "APP_URL", via: "APP_URL_PARAM"},                       // written by infra's WebStack (Amplify's address)
	{name: "TOKEN_SECRET", via: "TOKEN_SECRET_ARN", secret: true}, // generated by infra's ApiStack
}

// Resolve fetches, once, every value whose environment variable names a place in AWS, and
// returns a getenv that answers with them; everything else still comes from getenv. Locally
// nothing is named, so aws isn't called and may be nil. Errors name the variable and the
// parameter, never a value.
func Resolve(ctx context.Context, getenv func(string) string, aws AWS) (func(string) string, error) {
	got := map[string]string{}
	var errs []error
	for _, v := range fromAWS {
		where := getenv(v.via)
		if where == "" {
			continue
		}
		if getenv(v.name) != "" {
			errs = append(errs, fmt.Errorf("%s and %s are both set; set only one", v.name, v.via))
			continue
		}
		if aws == nil {
			errs = append(errs, fmt.Errorf("%s is set but there is no AWS client", v.via))
			continue
		}
		var val string
		var err error
		if v.secret {
			val, err = aws.Secret(ctx, where)
		} else {
			val, err = aws.Parameter(ctx, where)
		}
		val = strings.TrimSpace(val)
		switch {
		case err != nil:
			errs = append(errs, fmt.Errorf("%s=%s: %w", v.via, where, err))
		case val == "":
			errs = append(errs, fmt.Errorf("%s=%s is empty", v.via, where))
		default:
			got[v.name] = val
		}
	}
	if err := errors.Join(errs...); err != nil {
		return nil, fmt.Errorf("config: %w", err)
	}
	return func(name string) string {
		if v, ok := got[name]; ok {
			return v
		}
		return getenv(name)
	}, nil
}
